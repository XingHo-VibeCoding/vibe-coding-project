-- 前提：先跑 db/schema.sql 建好三张表
-- 跑法：控制台 → 数据库 → SQL 执行窗口，选中库后整体粘贴执行
--
-- 幂等：全部走 INSERT ... ON CONFLICT (id) DO UPDATE（主键是固定字符串 id）
--   → 重复执行不报错，且每行都会被覆盖成脚本里的那一份，跑十遍结果都一样。
--   created_at / updated_at 也显式写死，这样重跑后整表内容完全确定，
--   不会出现「跑两次、时间戳不同」导致对不上截图的情况。
--   （EXCLUDED.xxx 指「这次想插进去、但被主键冲突挡下的那一行」的新值）
--
-- 内容：6 个学期 / 22 条日程（16 门课 + 3 条独立日程 + 3 条循环日程）/ 10 条待办
--   全部围绕「2026 秋」这个当前学期（第一周周一 = 2026-09-07），
--   方便后面写 /api/list 时直接按学期筛。
-- ============================================================

